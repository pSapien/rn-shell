#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const rncli = require(require.resolve(path.resolve(__dirname, "node_modules", "@react-native-community", "cli")));

const { execSync } = require('child_process');

// const {linkAssets} = require(require.resolve(path.resolve(__dirname, "node_modules", 'react-native-asset')));

const toSnakeCase = str => {
  return str && str
    .match(/[A-Z]{2,}(?=[A-Z][a-z]+[0-9]*|\b)|[A-Z]?[a-z]+[0-9]*|[A-Z]|[0-9]+/g)
    .map(word => word.toLowerCase())
    .join('_');
};

// Create a run time config from the current working directory
const pkg = JSON.parse(fs.readFileSync(path.resolve('./package.json')));
const options = pkg["rn-shell"];

const buildConfig = {
  name: pkg.name,
  version: pkg.version,
  directory: process.cwd(), // The application working director
  main: pkg.main,       // Relative to directory
  dependencies: pkg.dependencies,

  displayName: options.name,
  moduleName: options.moduleName || toSnakeCase(options.name),
  id: options.id,
  buildNumber: options.buildNumber || 1,

  appIcon: path.resolve(process.cwd(), options.appIcon),

  splashIconSize: options.splashIconSize,
  splashIcon: options.splashIcon,
  splashBackColor: options.splashBackColor,

  appleTeam: options.appleTeam,
  androidFingerprint: options.androidFingerprint,

  deepLink: options.deepLink,
  universalLink: options.universalLink,
}

// Configuration Override
const config = pkg["rn-shell"];
if (config) {
  if (config.workspace) {
    buildConfig.workspaceRoot = path.resolve(config.workspace);
  }
}

const srcAssetsFolder = path.resolve('assets');
const destAssetsFolder = path.resolve(__dirname, "assets");

const srcAssets = fs.lstatSync(srcAssetsFolder);
if (srcAssets.isDirectory()) {
  // remove everything from the directoy first
  if (fs.existsSync(destAssetsFolder)) {
    const items = fs.readdirSync(destAssetsFolder);
    items.forEach(item => {
      if (item.startsWith(".")) return;
      fs.rmSync(path.join(destAssetsFolder, item), { recursive: true, force: true });
    });
  }

  const files = fs.readdirSync(srcAssetsFolder);
  files.forEach((file) => {
    // Ignore all hidden files
    if (file.startsWith('.')) return;
    fs.symlinkSync(path.resolve(srcAssetsFolder, file), path.resolve(destAssetsFolder, file));
  })
}

// Change the root directory to the Shell root
process.chdir(__dirname);


// Generate Defaults.xcconfig file for ios
fs.writeFileSync('Defaults.xcconfig', `
// Default ios config imported by Config.xcconfig
// Generated by react-native-shell cli
ENV_APP_BUNDLE_IDENTIFIER=${buildConfig.id}
ENV_APP_DISPLAY_NAME=${buildConfig.displayName}
ENV_APP_MODULE_NAME=${buildConfig.moduleName}
ENV_APP_MARKETING_VERSION=${buildConfig.version}
ENV_APP_BUILD_VERSION=${buildConfig.buildNumber}
`);

// Create symbolic link to assets folder for android
// fs.symlinkSync(destAssetsFolder, path.resolve('android/app/src/main/assets'));

fs.writeFileSync('.runtime.config.json', JSON.stringify(buildConfig, undefined, 2));


// Create app icon set
execSync("npx iconset create")



// Create splash screen assets
const icon = buildConfig.splashIcon || buildConfig.appIcon || './icons/app-icon.png'
const backColor = buildConfig.splashBackColor || '#f5f5f5';
const logoSize = buildConfig.splashIconSize || 128;

execSync(`npx react-native-bootsplash generate "${icon}" --background=${backColor} --logo-width=${logoSize}`)

// In case of a run-android command override the appId
if (process.argv[2] === 'run-android') {
  process.argv.push('--appId');
  process.argv.push(buildConfig.id);
}


if (config.universalLink) {
  let info = config.universalLink;
  // in most cases the universal Link is directly set to domain
  if (typeof info === 'string') {
    info = {
      paths: ["*"]
    }
  }

  if (!config.appleTeam) {
    console.warn('Apple TeamID (appleTeam) is not defined in configuration');
  }

  function withSlash(p) {
    if (p.startsWith('/')) return p;
    return '/' + p;
  }

  const aasa = {
    applinks: {
      apps: [],
      details: [{
        appIDs: [`${config.appleTeam}.${config.id}`],
        paths: [info.paths ? info.paths : "*"],
        components: info.paths ? info.paths.map(p => {
          if (p.startsWith("NOT")) {
            return {
              "/": withSlash(p.substring(3).trim()),
              exclude: true,
            }
          } else {
            return {
              "/": withSlash(p),
            }
          }
        }) : [{ "/": "/*" }],
      }]
    }
  };

  // Generate univeral link and deepLink
  fs.writeFileSync(
    path.resolve(buildConfig.directory, 'apple-app-site-association'),
    JSON.stringify(aasa, undefined, 2)
  );


  // Generate assetlinks.json
  if (config.androidFingerprint) {
    const fingerPrints = typeof config.androidFingerprint === 'string' ? [config.androidFingerprint] : config.androidFingerprint;

    // Requires multiple item for each fingerprint
    const links = fingerPrints.map(sha => ({
      relation: ["delegate_permission/common.handle_all_urls"],
      target: {
        namespace: "android_app",
        package_name: config.id,
        sha256_cert_fingerprints: [sha],
      },
    }));

    fs.writeFileSync(
      path.resolve(buildConfig.directory, 'assetlinks.json'),
      JSON.stringify(links, undefined, 2)
    );
  }
}


// run via react-native cli
rncli.run('react-native');
